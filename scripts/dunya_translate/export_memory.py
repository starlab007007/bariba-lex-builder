#!/usr/bin/env python3
"""Export the validated translation memory for the phone and the edge function.

  fitila_flutter/assets/data/dunya_memory.json        [fr, ba, grade] rows (Dart)
  supabase/functions/_shared/translation-memory.ts    pairs + lexicons (Deno)

ALL splits are exported (the deployed memory should know every attested
sentence); evaluation uses the train-only memory instead (see eval_translation).
"""

from __future__ import annotations

import json
from pathlib import Path

from dunya_text import fold_ba, fold_fr, tokens

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    data = ROOT / "data/translation"
    records = [json.loads(line) for line in (data / "parallel.jsonl").open(encoding="utf-8")]
    glossary = json.loads((data / "glossary.json").read_text(encoding="utf-8"))
    pairs = [r for r in records if r["kind"] != "word" and r["grade"] in ("A", "B")]
    pairs.sort(key=lambda r: (r["grade"], -len(r["sources"]), r["id"]))
    rows = [[r["fr"], r["ba"], r["grade"]] for r in pairs]

    out_app = ROOT / "fitila_flutter/assets/data/dunya_memory.json"
    out_app.write_text(json.dumps({"v": 1, "pairs": rows}, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")

    lex_ba, lex_fr = set(), set()
    for r in records:
        lex_ba.update(fold_ba(t) for t in tokens(r["ba"]))
        lex_fr.update(fold_fr(t) for t in tokens(r["fr"]))
    for g in glossary:
        lex_ba.update(fold_ba(t) for t in tokens(g["ba"]))
        for d in g["fr"]:
            lex_fr.update(fold_fr(t) for t in tokens(d))
    lex_ba.discard("")
    lex_fr.discard("")

    ts = (
        "// GENERATED by scripts/dunya_translate/export_memory.py — do not edit.\n"
        f"export const TM_PAIRS: Array<[string, string, string]> = {json.dumps(rows, ensure_ascii=False, separators=(',', ':'))};\n"
        f"export const LEXICON_BA = {json.dumps(' '.join(sorted(lex_ba)), ensure_ascii=False)};\n"
        f"export const LEXICON_FR = {json.dumps(' '.join(sorted(lex_fr)), ensure_ascii=False)};\n"
    )
    out_ts = ROOT / "supabase/functions/_shared/translation-memory.ts"
    out_ts.write_text(ts, encoding="utf-8")
    print(json.dumps({"pairs": len(rows), "lexicon_ba": len(lex_ba), "lexicon_fr": len(lex_fr),
                      "app_kb": out_app.stat().st_size // 1024, "ts_kb": out_ts.stat().st_size // 1024}))


if __name__ == "__main__":
    main()
