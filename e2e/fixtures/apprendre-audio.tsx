import React, {useState} from 'react';
import {createRoot} from 'react-dom/client';
import {MemoryRouter,Routes,Route} from 'react-router-dom';
import {AuthProvider} from '@/contexts/AuthContext';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import core from '@/data/apprendre_v2.json';
import scenes from '@/data/scenes_v2.json';
import {ApprendreContent,ScenesContent,type ApprendreContentJson,type ScenesContentJson} from '@/lib/apprendre/content';
import {ApprendreStore} from '@/lib/apprendre/store';
import {ScenesProgress} from '@/lib/apprendre/scenes';
import {type ApTask} from '@/lib/apprendre/tasks';
import FitilaLearn from '@/pages/fitila/FitilaLearn';
import FitilaLearnTheme from '@/pages/fitila/FitilaLearnTheme';
import BaribaAudioText from '@/components/fitila/BaribaAudioText';
import ClasseListenButton from '@/components/classe/ListenButton';
import {ApPronunciationProvider} from '@/components/apprendre/ApLinguisticText';
import ApFoundationScreen from '@/components/apprendre/ApFoundationScreen';
import ApSceneDetailScreen from '@/components/apprendre/ApSceneDetailScreen';
import ApSessionScreen from '@/components/apprendre/ApSessionScreen';
import ApSessionResultScreen from '@/components/apprendre/ApSessionResultScreen';
import '@/index.css';
const content=new ApprendreContent(core as unknown as ApprendreContentJson),sceneContent=new ScenesContent(scenes as unknown as ScenesContentJson);
const client=new QueryClient({defaultOptions:{queries:{retry:false}}});
client.setQueryData(['apprendre-content-bundle'],{content,scenesContent:sceneContent,source:'bundled'});
const store=ApprendreStore.open();store.progress.profile='fr';store.save();
const query=new URLSearchParams(location.search),view=query.get('view')||'audio';
const task=(partial:Partial<ApTask>):ApTask=>({kind:'choice',instruction:'Choisis la bonne réponse',prompt:'Cette banane est bonne',promptIsBariba:false,options:['Agɛdɛ ye ya do.','Nim mu boo yiba.'],optionsAreBariba:true,answer:'Agɛdɛ ye ya do.',orderAnswer:[],explain:'Agɛdɛ ye ya do. — Cette banane est bonne.',source:'Dictionnaire',verified:true,skill:'recall',...partial});
const tasks=[task({}),task({kind:'order',prompt:'Remets les mots dans l’ordre',options:['ye','Agɛdɛ','do','ya'],answer:'Agɛdɛ ye ya do',orderAnswer:['Agɛdɛ','ye','ya','do'],skill:'order'})];
function Fixture(){
 const [visible,setVisible]=useState(true);
 if(view==='classe')return <div className="p-4"><p>Prononciation de référence Classe</p><ClasseListenButton contentKey="classe/N1/lang/1/text"/></div>;
 if(view==='hub')return <FitilaLearn/>;
 if(view==='theme')return <Routes><Route path="/learn/theme/:id" element={<FitilaLearnTheme/>}/></Routes>;
 if(view==='foundation')return <ApFoundationScreen unit={content.foundations.find(unit=>unit.id===query.get('id'))||content.foundations[0]} store={store} content={content} onBack={()=>{}}/>;
 if(view==='scene')return <ApSceneDetailScreen scene={sceneContent.scenes.find(scene=>scene.id===query.get('id'))||sceneContent.scenes[0]} content={sceneContent} progress={ScenesProgress.open()} store={store} onBack={()=>{}} onNext={()=>{}}/>;
 if(view==='session')return <ApSessionScreen title="Séance d’écoute" tasks={tasks} store={store} sessionKey="audio-test" onClose={()=>{}}/>;
 if(view==='results')return <ApSessionResultScreen title="Résultat" result={{correct:0,total:2,skillTotals:{recall:1,order:1},skillCorrect:{},xpGained:0}} missed={tasks} store={store} foundationPassed={null} onClose={()=>{}}/>;
 return <div className="space-y-3 p-4"><button onClick={()=>setVisible(false)}>Quitter l’écoute</button>{visible&&<><BaribaAudioText text="Agɛdɛ ye ya do."/><BaribaAudioText text="Nim mu boo yiba."/>{view==='long'&&<BaribaAudioText text={('Agɛdɛ ye ya do. ').repeat(80)}/>}</>}</div>;
}
const theme=content.themes.find(theme=>theme.cards.length>120)||content.themes[0];
const route=view==='theme'?'/learn/theme/'+(query.get('id')||theme.id):'/learn';
createRoot(document.getElementById('root')!).render(<QueryClientProvider client={client}><AuthProvider><MemoryRouter initialEntries={[route]}><ApPronunciationProvider><div className="h-[100dvh] bg-[#F7F5EC]"><Fixture/></div></ApPronunciationProvider></MemoryRouter></AuthProvider></QueryClientProvider>);
